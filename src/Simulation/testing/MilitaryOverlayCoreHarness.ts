import {diffCanonicalWorldSave} from "../../Persistence/WorldSaveSchema";
import {militaryMilestones} from "../../UI/Components/FactionDetails/PersonChroniclePresentation";
import {getMilitaryArchive} from "../../UI/Components/FactionDetails/MilitaryPeoplePresentation";
import Phaser from "phaser";
/** Real Core/Phaser business regression, without screenshots or a visual Gate. */
import {createNaturalCore} from "./NaturalCoreHarness";
import Military from "../../Politics/MilitaryCommandRegistry";
import {resolveMilitaryCommandView} from "../../Game/MilitaryCommandOverlay";
import {SIMULATION_FIXED_STEP_MS} from "../SimulationDriver";
import worldRandom from "../WorldRandom";
import {exportWorldSave} from "../../Persistence/WorldSaveExporter";
import {hydrateWorldSave} from "../../Persistence/WorldSaveHydrator";
import {validateWorldSave} from "../../Persistence/WorldSaveValidator";
import Diplomacy from "../../Politics/Diplomacy";
import {isSiegePosition} from "../SiegeParticipants";
import {reconcileMilitaryPersonSelection,toggleMilitaryPerson} from "../../UI/Components/FactionDetails/MilitaryPersonSelection";
import WorldHistory from "../../History/WorldHistory";
import {composeMilitaryBiography} from "../../Politics/PersonBiography";

export async function runMilitaryOverlayCore(seed="military-overlay-z"){
  const {game,core}=await createNaturalCore(seed),checks:string[]=[];
  const check=(yes:unknown,label:string)=>{if(!yes)throw new Error(label);checks.push(label);};
  const month=()=>{for(let i=0;i<30;i++)(core as any).advanceLogicalStep(SIMULATION_FIXED_STEP_MS);core.scene.sys.events.emit("postupdate");};
  let command:string|undefined;
  for(let m=1;m<=240;m++){
    month();command=Military.getFormations().find(f=>resolveMilitaryCommandView(core,f.commandId)?.target)?.commandId;
    if(command)break;
  }
  if(!command)throw new Error("No natural active formation/target in first 20 years");
  let view=resolveMilitaryCommandView(core,command)!;
  const formation=Military.getFormations().find(f=>f.commandId===command)!;
  const person=Military.getPerson(formation.commanderPersonId)!;
  check(view.members.length===1&&person.appointments.at(-1)?.officeHistory?.[0]?.office==='XIAOWEI','natural initial colonel has exactly its own one real unit');
  const entry=core.logicalUnitRegistry.getEntry(view.members[0].unitId)!,initial={x:entry.player!.x,y:entry.player!.y},initialTarget=core.allCities.find(c=>c.id===formation.targetCityId)!;
  month();
  check(Math.hypot(entry.player!.x-initial.x,entry.player!.y-initial.y)>0||isSiegePosition(initialTarget,initial.x,initial.y,32,true),'single real Arcade commander executes movement or a verified contact hold');
  view=resolveMilitaryCommandView(core,command)!;
  const rng=JSON.stringify(worldRandom.exportState()),history=WorldHistory.getEvents().length;
  check(core.logicalGameplayAuthority===false,"actual default Arcade Core");
  check(view.members.every(m=>{const e=core.logicalUnitRegistry.getEntry(m.unitId)!;return m.x===e.player!.x&&m.y===e.player!.y;}),"live Player positions and real registry bindings");
  check(view.members.some(m=>{const s=core.logicalUnitRegistry.getEntry(m.unitId)!.state;return Math.hypot(m.x-s.logicalX,m.y-s.logicalY)>1;}),"natural motion diverges from registration snapshot");
  const factionPeople=Military.getPeople().filter(p=>p.factionId===person.factionId);
  const liveIds=new Set(factionPeople.filter(p=>core.teams.some(t=>[...t.users].some(u=>u.matchesMilitaryLife(p)))).map(p=>p.personId));
  const selection=reconcileMilitaryPersonSelection(undefined,person.factionId,factionPeople,Military.getFormations(),liveIds);
  check(selection.expandedIds.length===factionPeople.filter(p=>p.status==="ACTIVE"&&liveIds.has(p.personId)&&Military.getFormations().some(f=>f.status==="ACTIVE"&&f.commanderPersonId===p.personId)).length,"all real active commanders open by default");
  check(Boolean(selection.focusedId),"one real commander receives automatic map focus");
  const focused=Military.getFormations().find(f=>f.status==="ACTIVE"&&f.commanderPersonId===selection.focusedId)!;
  check(core.showMilitaryCommand(focused.commandId,true),"default selection automatically highlights a real formation");
  const changed=toggleMilitaryPerson(selection,person.personId,true);
  check(changed.focusedId===person.personId&&changed.expandedIds.length===selection.expandedIds.length,"active header focus preserves all current biographies");
  const initialOffice=WorldHistory.getEvents().find(e=>e.id===person.appointments.at(-1)?.officeHistory?.[0]?.eventId)!;
  check(typeof initialOffice.rulerId==="string"&&typeof initialOffice.metadata?.authorizingRulerTitle==="string","actual formal-state grant freezes its contemporary issuing ruler");
  check(person.appointments.at(-1)?.officeHistory?.[0]?.office==="XIAOWEI"&&WorldHistory.getEvents().some(e=>e.id===person.appointments.at(-1)?.officeHistory?.[0]?.eventId),"real User appointment grants canonical initial office");
  check(core.focusMilitaryFormation(command),"real Core focuses and highlights actual formation");
  check(core.focusMilitaryTargetCity(view.target!.cityId,command),"target focus uses the shared command overlay lifecycle");
  core.showMilitaryCommand(command,true);
  const overlay=(core as any).militaryCommandOverlay,g=overlay.graphics;
  check(g instanceof Phaser.GameObjects.Graphics&&!g.input,"real noninteractive Phaser Graphics");
  for(let i=0;i<120;i++)overlay.update();check(overlay.graphics===g,"one Graphics reused across presentation updates");
  core.logicalGameplayAuthority=true;
  check(resolveMilitaryCommandView(core,command)!.members.every(m=>m.x===core.logicalUnitRegistry.getEntry(m.unitId)!.state.logicalX),"logical-mode coordinate authority");
  core.logicalGameplayAuthority=false;
  const fullEntries=Military.getChronicle(person,core.simulator!.year,person.factionId);
  const reading=militaryMilestones(person,fullEntries,WorldHistory.getEventsForFaction(person.factionId));
  check(fullEntries.some(e=>e.source.startsWith("military-order-issued"))&&!reading.some(e=>e.source.startsWith("military-order-issued")),"ordinary orders retained in the archive but omitted from public milestones");
  check(reading.some(e=>e.text.includes("始任")&&e.text.includes("校尉"))&&!reading.some(e=>e.text.includes("据本次任职")),"formal initial office is readable without zero-month audit wording");
  const archive=getMilitaryArchive(factionPeople,person.factionId,Military.getFormations(),liveIds);
  check(archive.currentPeople.some(p=>p.personId===person.personId)&&archive.visiblePeople.includes(person),"real living commander remains visible in the chronological archive");
  const bio=composeMilitaryBiography(person,Military.getChronicle(person,core.simulator!.year,person.factionId),person.factionId);
  check(bio.life.length>0&&Military.getChronicle(person,core.simulator!.year).some(e=>e.source.startsWith("military-appointment")),"real appointment enters biography");
  check(JSON.stringify(worldRandom.exportState())===rng&&WorldHistory.getEvents().length===history,"UI projections preserve RNG and canonical history");
  const target=core.allCities.find(c=>c.id===view.target!.cityId)!;
  // Exercise a real relation transition, not a fake target or substitute battle.
  Diplomacy.setRelation({factionAId:person.factionId,factionBId:target.ownerFactionId,status:"TRUCE",reason:"WAR_EXHAUSTION_TRUCE",startedMonth:core.simulator!.year,expiresMonth:core.simulator!.year+24});
  check(!resolveMilitaryCommandView(core,command)?.target,"real truce removes hostile target");overlay.update();
  core.selectFaction(undefined);check(!overlay.selection,"country selection clears overlay");
  core.setWorldRunning(false);
  core.showMilitaryCommand(command,true);
  const save=exportWorldSave(core);
  check(validateWorldSave(save).valid,"strict V20 real Core export");
  hydrateWorldSave(core,JSON.parse(JSON.stringify(save)));
  check(!overlay.selection&&g.commandBuffer.length===0,"hydration clears selected overlay and drawing");
  check(core.scene.physics.world.pendingDestroy.size===0,"hydration drains old Phaser bodies before rebuilding the world");
  check(validateWorldSave(exportWorldSave(core)).valid,"strict V20 real Core hydration");
  check(WorldHistory.getEvents().find(e=>e.id===initialOffice.id)?.metadata?.authorizingRulerTitle===initialOffice.metadata?.authorizingRulerTitle,"frozen issuing ruler survives real Core hydration");
  check(Military.getPerson(person.personId)?.personalName===person.personalName,"person identity and recorded name survive load");
  const continueOnce=()=>{
    hydrateWorldSave(core,JSON.parse(JSON.stringify(save)));
    check(core.scene.physics.world.pendingDestroy.size===0,"repeated hydration leaves no destroyed physics bodies");
    core.setWorldRunning(true);for(let m=0;m<12;m++)month();core.setWorldRunning(false);
    return exportWorldSave(core);
  };
  const first=continueOnce(),second=continueOnce();
  check(diffCanonicalWorldSave(first,second).matched,"same Arcade snapshot resumes deterministically across repeated loads");
  check(validateWorldSave(second).valid,"12-month post-load production continuation");
  const result={seed,checks,commandId:command,personId:person.personId,memberCount:view.members.length,worldMonth:core.simulator!.year,saveSchemaVersion:save.saveSchemaVersion};
  game.destroy(true);return result;
}
